"""
Вспомогательные утилиты, не относящиеся ни к одному конкретному модулю.

Здесь намеренно нет тяжёлых импортов (torch, transformers и т. п.):
функции из этого файла должны быть пригодны для использования и в
лёгких сценариях (тесты, скрипты подготовки данных), и внутри основных
модулей.
"""

from __future__ import annotations

import re
from typing import List


def split_to_facts(text: str, min_length: int = 5) -> List[str]:
    """Разбить текст на список «фактов»-предложений.

    Используется для подготовки базы знаний (поле ``knowledge`` из
    HaluEval) к подаче в :class:`FactChecker`. Разбиение выполняется по
    знакам конца предложения (``.``, ``!``, ``?``) с последующим
    удалением хвостовых пробелов и отбрасыванием слишком коротких
    фрагментов.

    Не использует spaCy: на чистых текстах из Википедии (HaluEval)
    регулярка справляется не хуже sentence-сегментатора и не требует
    инициализации модели — это удобно для лёгких сценариев и тестов.

    Параметры:
        text: исходный текст базы знаний.
        min_length: минимальная допустимая длина предложения (в
            символах) — короткие фрагменты вроде «No.» или «Mr.»
            отфильтровываются.

    Возвращает:
        Список непустых предложений в порядке их появления.
    """
    if not text:
        return []
    parts = re.split(r"(?<=[.!?])\s+", text)
    return [p.strip() for p in parts if len(p.strip()) >= min_length]
